def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-id", required=True)
    ap.add_argument("--bronze", default=str(ROOT / "exports" / "bronze"))
    ap.add_argument("--out", default=str(ROOT / "docs" / "field_inventory.md"))
    a = ap.parse_args(argv)
    stats = inventory(Path(a.bronze), a.run_id)
    Path(a.out).write_text(render(stats, a.run_id))
    for (src, t), st in sorted(stats.items()):
        print(src, t, st["n"], "records", len(st["paths"]), "paths")


if __name__ == "__main__":
    main()
