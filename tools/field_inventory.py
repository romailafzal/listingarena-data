def is_empty(v) -> bool:
    return v is None or v == "" or v == [] or v == {}


def walk(obj, prefix, out: dict):
    """Collect leaf values per path; lists of dicts become path[]."""
    if isinstance(obj, dict):
        if not obj:
            out.setdefault(prefix, []).append(None)
        for k, v in obj.items():
            walk(v, f"{prefix}.{k}" if prefix else k, out)
    elif isinstance(obj, list) and obj and all(isinstance(x, dict) for x in obj):
        for x in obj:
            walk(x, prefix + "[]", out)
    else:
        out.setdefault(prefix, []).append(obj)


def records_of(source: str, ltype: str, response) -> list:
    if source == "realtor":
        return parse_search(response)[0]
    return parse_response(response, ltype)[0]


def inventory(bronze: Path, run_id: str):
    stats = {}  # (source, type) -> {"n": int, "paths": {path: [populated_records, example]}}
    for f in sorted(bronze.glob(f"*/*/*/{run_id}/*.json.gz")):
        source = f.parts[-5]
        with gzip.open(f, "rt") as fh:
            page = json.load(fh)
        ltype = page["listing_type"]
        st = stats.setdefault((source, ltype), {"n": 0, "paths": defaultdict(lambda: [0, None]), "seen": set()})
        for rec in records_of(source, ltype, page["response"]):
            rid = json.dumps(rec.get("property_id") or rec.get("propertyId") or (rec.get("homeData") or {}).get("propertyId"))
            if rid in st["seen"]:
                continue
            st["seen"].add(rid)
            st["n"] += 1
            leaves = {}
            walk(rec, "", leaves)
            for path, vals in leaves.items():
                slot = st["paths"][path]
                nonempty = [v for v in vals if not is_empty(v)]
                if nonempty:
                    slot[0] += 1
                    if slot[1] is None:
                        slot[1] = nonempty[0]
                else:
                    slot[0] += 0
    return stats


def mapped(source: str, path: str) -> bool:
    base = path.replace("[]", "")
    return any(path == m or path.startswith(m + ".") or path.startswith(m + "[]") or base == m.replace("[]", "")
               or base.startswith(m.replace("[]", "") + ".") for m in MAPPED[source])


def fmt(v) -> str:
    s = json.dumps(v, ensure_ascii=False) if not isinstance(v, str) else v
    s = s.replace("|", "\\|").replace("\n", " ")
    return (s[:60] + "...") if len(s) > 63 else s


def render(stats, run_id: str) -> str:
    out = [f"# Field inventory (live run `{run_id}`)\n",
           "Generated by `python -m tools.field_inventory --run-id " + run_id + "` from bronze search pages "
           "(Austin County TX 48015 + Travis County TX 48453, first 2 pages per type). "
           "`%` = share of unique records where the path is non-empty. `app` = mapped into an app `COLS` column "
           "(listingarena-app/lib/db.js); `-` = **not stored by the app today**. Paths ending in `[]` are list items.\n",
           "App COLS: " + ", ".join(f"`{c}`" for c in APP_COLS) + "\n"]
    out.append("## Summary\n\n| source | type | records | raw paths | populated paths | mapped to app | not stored |\n|---|---|---|---|---|---|---|")
    for (src, t), st in sorted(stats.items()):
        paths = st["paths"]
        pop = [p for p, (c, _) in paths.items() if c]
        m = [p for p in pop if mapped(src, p)]
        out.append(f"| {src} | {t} | {st['n']} | {len(paths)} | {len(pop)} | {len(m)} | {len(pop) - len(m)} |")
    out.append("")
    out.append(SUMMARY_NOTES)
    for (src, t), st in sorted(stats.items()):
        out.append(f"\n## {src} / {t} ({st['n']} records)\n\n| path | % | app | example |\n|---|---|---|---|")
        for path, (c, ex) in sorted(st["paths"].items()):
            pct = 100 * c / st["n"] if st["n"] else 0
            out.append(f"| `{path}` | {pct:.0f} | {'app' if mapped(src, path) else '-'} | {fmt(ex) if ex is not None else ''} |")
    return "\n".join(out) + "\n"


